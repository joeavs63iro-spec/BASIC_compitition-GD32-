#include "car_reed.h"

//全局变量

//-------------------------------------------------------------------------------------------------------------------
// @brief        智能车干簧管初始化
// @param        void
// @return       void
// Sample usage:        reed_init();
//-------------------------------------------------------------------------------------------------------------------
void reed_init(void)
{
    gpio_pin_init(REED_PORT, REED_MODE, REED_PIN); 
}

//-------------------------------------------------------------------------------------------------------------------
// @brief        智能车磁标检测
// @param        void
// @return       void
// Sample usage:        reed_check();//当干簧管检测到地面磁标时，标志位置1，否则为0。
//-------------------------------------------------------------------------------------------------------------------
uint8_t reed_check(void)
{
    if(RESET == gpio_get_input(REED_PORT, REED_PIN))
    {
        return 1;
    }
    else
    {
        return 0;
    }
		
}
